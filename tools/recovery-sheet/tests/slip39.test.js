test("combine validates input and does not echo mnemonic words in errors", async () => {
  const secret = webcrypto.getRandomValues(new Uint8Array(16));
  const a = await splitMasterSecret({ masterSecret: secret, threshold: 2, shareCount: 3, crypto: webcrypto });
  const b = await splitMasterSecret({ masterSecret: secret, threshold: 2, shareCount: 3, crypto: webcrypto });
  await assert.rejects(combineMnemonics([], "", webcrypto), /empty/);
  await assert.rejects(combineMnemonics(a.slice(0, 2), "", undefined), /Web Crypto/);
  await assert.rejects(combineMnemonics(a.slice(0, 2), "\u00ff", webcrypto), /printable ASCII/);
  await assert.rejects(combineMnemonics([a[0], 42], "", webcrypto), /Mnemonic 2: Mnemonic must be a string/);
  if (decodeMnemonic(a[0]).identifier !== decodeMnemonic(b[0]).identifier) {
    await assert.rejects(combineMnemonics([a[0], b[1]], "", webcrypto), /same 2 words/);
  }

  const words = a[1].split(" ");
  const tampered = words.slice();
  tampered[7] = WORDLIST[(WORDLIST.indexOf(words[7]) + 1) % 1024];
  const notAWord = words.slice();
  notAWord[5] = "bitcoin";
  for (const [list, pattern] of [
    [[a[0], tampered.join(" ")], /Mnemonic 2: Invalid mnemonic checksum/],
    [[a[0], notAWord.join(" ")], /Mnemonic 2: Word 6 is not in the SLIP-39 wordlist/],
    [[a[0], words.slice(0, 19).join(" ")], /at least 20 words/],
  ]) {
    await assert.rejects(combineMnemonics(list, "", webcrypto), (error) => {
      assert.match(error.message, pattern);
      const template = new Set(["order", "length", "have"]); // wordlist words that occur in the fixed message texts
      for (const w of [...words, "bitcoin"]) {
        if (!template.has(w)) assert.ok(!error.message.toLowerCase().split(/\W+/).includes(w), `error leaks "${w}"`);
      }
      return true;
    });
  }
});

test("combine accepts any case, extra whitespace, 4-letter prefixes and exact duplicates", async () => {
  const secret = webcrypto.getRandomValues(new Uint8Array(16));
  const m = await splitMasterSecret({ masterSecret: secret, threshold: 2, shareCount: 3, crypto: webcrypto });
  const messy = `  ${m[0].toUpperCase().replace(/ /g, "\n\t ")}  `;
  const prefixed = m[2].split(" ").map((w, i) => (i % 2 ? w.slice(0, 4) : w.slice(0, Math.max(4, w.length - 1)))).join(" ");
  assert.deepEqual(await combineMnemonics([messy, prefixed], "", webcrypto), secret);
  assert.deepEqual(await combineMnemonics([m[0], m[0], m[1]], "", webcrypto), secret);
  assert.deepEqual(mnemonicToWords(prefixed), m[2].split(" "));
  // Too-short fragments and fragments that are not a word's beginning are rejected.
  assert.throws(() => mnemonicToWords("aca"), /Word 1/);
  assert.throws(() => mnemonicToWords("academix"), /Word 1/);
  assert.throws(() => mnemonicFromPrefixes("ACADACI"), /multiple of 4/);
  assert.throws(() => mnemonicFromPrefixes("ACADXXXX"), /Prefix 2/);
  assert.throws(() => wordPrefixes(m[0].split(" ").reverse().join(" ")), /checksum/);
});
