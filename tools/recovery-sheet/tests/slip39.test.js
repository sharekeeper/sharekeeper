test("GF(256) log/exp tables use generator x+1 and the Rijndael polynomial", () => {
  const { EXP_TABLE, LOG_TABLE, gfMul } = _internals;
  assert.equal(EXP_TABLE[0], 1);
  assert.equal(EXP_TABLE[1], 3);
  assert.equal(EXP_TABLE[254], 0xf6); // 3^-1
  assert.equal(new Set(EXP_TABLE).size, 255);
  for (let i = 0; i < 255; i += 1) assert.equal(LOG_TABLE[EXP_TABLE[i]], i);
  // Carry-less multiply then reduce modulo x^8 + x^4 + x^3 + x + 1.
  const slowMul = (a, b) => {
    let p = 0;
    for (let i = 0; i < 8; i += 1) if ((b >> i) & 1) p ^= a << i;
    for (let bit = 14; bit >= 8; bit -= 1) if ((p >> bit) & 1) p ^= 0x11b << (bit - 8);
    return p;
  };
  for (let a = 0; a < 256; a += 1) {
    for (let b = 0; b < 256; b += 1) {
      const viaTables = a === 0 || b === 0 ? 0 : EXP_TABLE[(LOG_TABLE[a] + LOG_TABLE[b]) % 255];
      const ct = gfMul(a, b);
      if (ct !== viaTables || ct !== slowMul(a, b)) assert.fail(`gfMul(${a}, ${b})`);
    }
  }
  assert.equal(gfMul(0x57, 0x83), 0xc1); // FIPS-197 section 4.2 example
});

test("interpolation returns known points and rejects duplicate indices", () => {
  const { interpolate } = _internals;
  const a = { x: 1, data: Uint8Array.of(7, 8) };
  const b = { x: 2, data: Uint8Array.of(9, 10) };
  assert.deepEqual(interpolate([a, b], 2), b.data);
  // Degree-1 polynomial through two points is consistent at a third point.
  const c = { x: 5, data: interpolate([a, b], 5) };
  assert.deepEqual(interpolate([a, c], 2), b.data);
  assert.throws(() => interpolate([a, { x: 1, data: Uint8Array.of(1, 2) }], 0), /unique/);
  assert.throws(() => interpolate([a, { x: 3, data: Uint8Array.of(1) }], 0), /same length/);
});

test("RS1024 detects every single-word substitution and binds the customization string", () => {
  const { rs1024VerifyChecksum } = _internals;
  const valid = VECTORS[41][1][0]; // extendable, 20 words
  const indices = mnemonicToWords(valid).map((w) => WORDLIST.indexOf(w));
  assert.ok(rs1024VerifyChecksum(indices, true));
  assert.equal(rs1024VerifyChecksum(indices, false), false);
  for (let pos = 0; pos < indices.length; pos += 1) {
    for (let v = 0; v < 1024; v += 1) {
      if (v === indices[pos]) continue;
      const changed = indices.slice();
      changed[pos] = v;
      if (rs1024VerifyChecksum(changed, true)) assert.fail(`undetected substitution at ${pos}`);
    }
  }
});

test("bit packing round-trips and enforces zero padding", () => {
  const { bytesToWordIndices, wordIndicesToBytes } = _internals;
  for (const len of [16, 32]) {
    const bytes = webcrypto.getRandomValues(new Uint8Array(len));
    const words = bytesToWordIndices(bytes, Math.ceil((len * 8) / 10));
    const pad = (words.length * 10) % 16;
    assert.deepEqual(wordIndicesToBytes(words, pad), bytes);
    const bad = words.slice();
    bad[0] |= 1 << 9;
    assert.equal(wordIndicesToBytes(bad, pad), null);
  }
});

