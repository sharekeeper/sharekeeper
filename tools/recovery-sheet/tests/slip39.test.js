function combinations(items, k) {
  if (k === 0) return [[]];
  if (items.length < k) return [];
  const [head, ...rest] = items;
  return [...combinations(rest, k - 1).map((c) => [head, ...c]), ...combinations(rest, k)];
}

/** Same byte stream as scripts/slip39-crosscheck.py: SHA-256(seed || uint32be(counter)) blocks. */
function streamCrypto(seed) {
  let counter = 0;
  let buf = Buffer.alloc(0);
  const calls = [];
  return {
    calls,
    subtle: webcrypto.subtle,
    getRandomValues(arr) {
      calls.push(arr.length);
      while (buf.length < arr.length) {
        const c = Buffer.alloc(4);
        c.writeUInt32BE(counter++);
        buf = Buffer.concat([buf, createHash("sha256").update(Buffer.concat([Buffer.from(seed), c])).digest()]);
      }
      arr.set(buf.subarray(0, arr.length));
      buf = buf.subarray(arr.length);
      return arr;
    },
  };
}

