test("split/combine round-trip for every 2 <= t <= n <= 5 and every t-subset", async () => {
  for (let n = 2; n <= 5; n += 1) {
    for (let t = 2; t <= n; t += 1) {
      const secret = webcrypto.getRandomValues(new Uint8Array(16));
      const copy = secret.slice();
      const mnemonics = await splitMasterSecret({ masterSecret: secret, threshold: t, shareCount: n, crypto: webcrypto });
      assert.deepEqual(secret, copy, "input must not be modified");
      assert.equal(mnemonics.length, n);
      for (const m of mnemonics) assert.equal(m.split(" ").length, 20);
      const indices = [...Array(n).keys()];
      for (const subset of combinations(indices, t)) {
        const picked = subset.map((i) => mnemonics[i]);
        assert.deepEqual(await combineMnemonics(picked, "", webcrypto), secret, `${t}-of-${n} ${subset}`);
        assert.deepEqual(await combineMnemonics(picked.reverse(), "", webcrypto), secret);
      }
      for (const subset of combinations(indices, t - 1)) {
        await assert.rejects(combineMnemonics(subset.map((i) => mnemonics[i]), "", webcrypto), /Insufficient number of mnemonics: \d+ required/);
      }
      if (t < n) {
        // The spec requires exactly T member shares.
        await assert.rejects(combineMnemonics(mnemonics.slice(0, t + 1), "", webcrypto), /Wrong number of mnemonics/);
      }
    }
  }
});

test("defaults: extendable, iteration exponent 1, single group, 20 words, 80 prefix letters", async () => {
  assert.equal(DEFAULT_EXTENDABLE, true);
  assert.equal(DEFAULT_ITERATION_EXPONENT, 1);
  const secret = webcrypto.getRandomValues(new Uint8Array(16));
  const mnemonics = await splitMasterSecret({ masterSecret: secret, threshold: 3, shareCount: 5, crypto: webcrypto });
  const decoded = mnemonics.map(decodeMnemonic);
  decoded.forEach((share, i) => {
    assert.equal(share.extendable, true);
    assert.equal(share.iterationExponent, 1);
    assert.equal(share.identifier, decoded[0].identifier);
    assert.ok(share.identifier >= 0 && share.identifier < 1 << 15);
    assert.equal(share.groupIndex, 0);
    assert.equal(share.groupThreshold, 1);
    assert.equal(share.groupCount, 1);
    assert.equal(share.memberIndex, i);
    assert.equal(share.memberThreshold, 3);
    assert.equal(share.value.length, 16);
    assert.equal(share.wordCount, 20);
  });
  for (const m of mnemonics) {
    const prefixes = wordPrefixes(m);
    assert.match(prefixes, /^[A-Z]{80}$/);
    assert.equal(mnemonicFromPrefixes(prefixes), m);
    assert.equal(mnemonicFromPrefixes(prefixes.match(/.{4}/g).join(" ").toLowerCase()), m);
  }
  // The first two words (identifier + ext + e) are shared by all shares.
  assert.equal(new Set(mnemonics.map((m) => m.split(" ").slice(0, 2).join(" "))).size, 1);
});

test("1-of-2: two 1-of-1 groups with group threshold 1; each share alone recovers", async () => {
  for (const [length, words] of [[16, 20], [32, 33]]) {
    const secret = webcrypto.getRandomValues(new Uint8Array(length));
    const calls = [];
    const crypto = { subtle: webcrypto.subtle, getRandomValues: (arr) => (calls.push(arr.length), webcrypto.getRandomValues(arr)) };
    const mnemonics = await splitMasterSecret({ masterSecret: secret, threshold: 1, shareCount: 2, crypto });
    assert.deepEqual(calls, [2], "only the identifier is random");
    assert.equal(mnemonics.length, 2);
    assert.notEqual(mnemonics[0], mnemonics[1]);
    mnemonics.forEach((m, i) => {
      assert.equal(m.split(" ").length, words);
      assert.match(wordPrefixes(m), new RegExp(`^[A-Z]{${words * 4}}$`));
      const d = decodeMnemonic(m);
      assert.equal(d.groupIndex, i);
      assert.equal(d.groupThreshold, 1);
      assert.equal(d.groupCount, 2);
      assert.equal(d.memberIndex, 0);
      assert.equal(d.memberThreshold, 1);
      assert.equal(d.extendable, true);
      assert.equal(d.iterationExponent, 1);
    });
    assert.deepEqual(await combineMnemonics([mnemonics[0]], "", webcrypto), secret);
    assert.deepEqual(await combineMnemonics([mnemonics[1]], "", webcrypto), secret);
    assert.deepEqual(await combineMnemonics([mnemonics[1], mnemonics[1]], "", webcrypto), secret, "exact duplicate counts once");
    // The spec requires exactly GT (= 1) groups, so supplying both shares is rejected, as in the reference.
    await assert.rejects(combineMnemonics(mnemonics, "", webcrypto), /Wrong number of mnemonic groups: exactly 1 required, 2 provided/);
  }
});

test("256-bit secrets give 33-word shares; non-extendable and other exponents round-trip", async () => {
  const secret = webcrypto.getRandomValues(new Uint8Array(32));
  for (const [extendable, iterationExponent] of [[true, 0], [false, 0], [false, 2]]) {
    const mnemonics = await splitMasterSecret({ masterSecret: secret, threshold: 2, shareCount: 3, passphrase: "TREZOR", extendable, iterationExponent, crypto: webcrypto });
    for (const m of mnemonics) {
      assert.equal(m.split(" ").length, 33);
      assert.match(wordPrefixes(m), /^[A-Z]{132}$/);
      const d = decodeMnemonic(m);
      assert.equal(d.extendable, extendable);
      assert.equal(d.iterationExponent, iterationExponent);
    }
    assert.deepEqual(await combineMnemonics([mnemonics[2], mnemonics[0]], "TREZOR", webcrypto), secret);
    const wrong = await combineMnemonics([mnemonics[2], mnemonics[0]], "TREZOS", webcrypto);
    assert.notDeepEqual(wrong, secret, "a wrong passphrase gives a different secret, not an error");
  }
});

