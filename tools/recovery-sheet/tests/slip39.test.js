const VECTORS_SHA256 = "13ebecebdd869dd2bc2cdf69e7ce3a158cf106cac76c39d17682b1c6cdabbdc4";
// Generated by scripts/slip39-crosscheck.py --write (python shamir-mnemonic 0.3.0)
